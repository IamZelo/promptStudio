"""Data contracts and schemas for multi-agent communication.

Using Pydantic models ensures strict typing and guaranteed JSON structure
from Gemini's structured output generation.
"""

from __future__ import annotations

from typing import List
from pydantic import BaseModel, Field


class FileSpec(BaseModel):
    """Specification of a single file in the project blueprint."""
    path: str = Field(
        description="Relative file path (e.g., 'src/calculator.py', 'tests/test_calculator.py', 'README.md')"
    )
    description: str = Field(
        description="Detailed responsibilities, public classes/functions, inputs, outputs, and edge cases"
    )
    dependencies: List[str] = Field(
        default_factory=list,
        description="List of other project files or external third-party libraries this file depends on"
    )


class ArchitectureBlueprint(BaseModel):
    """Complete project architectural blueprint generated by the Architect Agent."""
    project_name: str = Field(
        description="Short slug or directory name for the project (e.g. 'quicknote-cli')"
    )
    summary: str = Field(
        description="High-level overview of the application architecture, design patterns, and components"
    )
    tech_stack: List[str] = Field(
        default_factory=list,
        description="Technologies, frameworks, and core libraries used"
    )
    files: List[FileSpec] = Field(
        description="Ordered list of files to generate (foundation files first, followed by consumers)"
    )


class GeneratedFile(BaseModel):
    """Source code and explanation for a generated file produced by the Developer Agent."""
    path: str = Field(
        description="Target relative file path matching the blueprint"
    )
    code: str = Field(
        description="Complete, valid, production-ready source code with no TODOs or omitted sections"
    )
    summary: str = Field(
        description="Brief summary of implemented functionality"
    )
